const { boot, wait, api, checker } = require('./h.js');
const { ok, done } = checker();
(async () => {
  const w = await boot({}); const A = api(w);
  const hit = []; w.Element.prototype.scrollIntoView = function () { hit.push(this.id); };
  await wait(100);
  ok(/v0\.6/.test(A.$('appVersion').textContent) && A.$('appVersion').textContent === 'v0.6', 'title page shows version v0.6: ' + A.$('appVersion').textContent);
  ok(!A.$('screen-start').hidden && !A.$('rulesBtn').hidden && A.$('rulesBtn').classList.contains('center'), 'RULES button (center top) is on the title page when logged out');
  A.click(A.$('rulesBtn')); await wait(50);
  ok(!A.$('screen-rules').hidden && A.vis().join() === 'rules', 'RULES opens the rulebook');
  ok(A.$('rulesBtn').hidden, 'the RULES button hides on the rules page');
  ok(w.document.body.classList.contains('on-rules'), 'rules page gets the dark-gray background class');
  const doc = A.$('rulesDoc');
  ok(doc.querySelector('h1').textContent === 'Bloodsoup Hell Rules 0.3', 'title');
  const heads = [...doc.querySelectorAll('h2[id],h3[id]')].filter((h) => !h.closest('.rtoc'));
  const links = [...doc.querySelectorAll('.rtoc a[data-goto]')];
  ok(heads.length === 35 && links.length === 35, `35 headings, 35 contents links (${heads.length}/${links.length})`);
  ok(links.every((a) => doc.querySelector('#' + a.dataset.goto)), 'every contents link points at a real heading');
  ok(links.every((a, i) => a.textContent === heads[i].firstChild.textContent), 'contents entries are in order and match the headings');
  const sub = doc.querySelectorAll('.rtoc li li').length;
  ok(sub === 25 - 0 || sub > 10, 'sub-headings are nested in the contents (' + sub + ')');
  const pick = links.find((a) => a.textContent === 'Combo Attacks');
  let prevented = false; const ev = new w.MouseEvent('click', { bubbles: true, cancelable: true }); pick.dispatchEvent(ev); prevented = ev.defaultPrevented;
  ok(hit.pop() === 'rules-combo-attacks' && w.document.activeElement.id === 'rules-combo-attacks' && prevented, 'tapping "Combo Attacks" scrolls to and focuses that heading');
  ok(w.location.hash === '#rules', 'and the address stays on the rules page');
  const tops = doc.querySelectorAll('.totop'); tops[3].dispatchEvent(new w.MouseEvent('click', { bubbles: true, cancelable: true }));
  ok(hit.pop() === 'rules-top', 'each heading has a ^ CONTENTS link back to the top');
  ok(doc.querySelectorAll('table').length === 7 && doc.querySelectorAll('th').length > 10, 'all 7 tables came across, with header rows');
  ok(/Welcome to Endolore/.test(doc.textContent) && /Explode Tokens/.test(doc.textContent), 'text is there');
  A.click(A.$('rulesBack')); await wait(50);
  ok(A.vis().join() === 'start' && !A.$('rulesBtn').hidden, 'BACK returns to where you came from');
  // logged in
  await A.signUp(); await wait(100);
  ok(A.vis().join() === 'home' && !A.$('rulesBtn').hidden, 'RULES is also on every logged-in screen');
  A.click(A.$('rulesBtn')); await wait(50);
  ok(A.vis().join() === 'rules' && !A.$('logoutBtn').hidden === false, 'logged-in users can open the rules (no redirect home)');
  A.click(A.$('rulesBack')); await wait(50);
  ok(A.vis().join() === 'home', 'BACK returns to Home');
  A.go('options'); await wait(50); A.click(A.$('rulesBtn')); await wait(50); A.click(A.$('rulesBack')); await wait(50);
  ok(A.vis().join() === 'options', 'BACK returns to Options');
  ok(!w.document.body.classList.contains('on-rules'), 'dark-gray page only on the rules');
  ok(w.__errors.length === 0, 'no script errors: ' + w.__errors.join('|'));
  done();
})();
