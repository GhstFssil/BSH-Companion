const { boot, wait, api, checker } = require('./h.js');
const { ok, done } = checker();
(async () => {
  const w = await boot({}); const A = api(w);
  await A.signUp();
  const b = w.BSHBackend.create(w.BSH_CONFIG); await b.init();
  const c = w.BSH.blankCharacter(); c.id = w.crypto.randomUUID(); c.info.name = 'T'; c.items = [{ name: 'Wand', qty: 1, charges: 7, desc: '' }, { name: 'Rock', qty: 1, charges: 4, desc: '' }];
  await b.saveCharacter(c);
  A.go('characters'); await wait(150); A.go('character-' + c.id); await wait(100); A.tab('items'); await wait(30);
  const card = (n = 0) => A.d.querySelectorAll('#panel-items .item')[n];
  const open = (n) => { if (card(n).querySelector('.idesc').hidden) A.click(card(n).querySelector('.chev')); };
  const ev = (el, v) => { el.value = v; el.dispatchEvent(new w.Event('input', { bubbles: true })); };
  ok(card(0).querySelectorAll('.iline input.num').length === 1, 'non-magic item has no charges field (qty only)');
  open(0);
  const mcb = () => card(0).querySelector('.iflags input[aria-label="Magic"]');
  mcb().checked = true; mcb().dispatchEvent(new w.Event('change', { bubbles: true })); await wait(30); open(0);
  const labels = [...card(0).querySelectorAll('.wpgrid .lbl')].map((x) => x.textContent);
  ok(labels.join('|') === 'Type|Attunement|Max Charges|Effect', 'magic fields: ' + labels.join('|'));
  ok(!!card(0).querySelector('.wpgrid input[type=checkbox][aria-label="Spellbook"]'), 'Spellbook checkbox');
  const ch = () => card(0).querySelector('[aria-label="Charges (0 to Max Charges)"]');
  ok(!!ch(), 'charges field appears for magic item');
  ok(ch().value === '0' && ch().max === '0', 'old 7 charges clamped to max 0: ' + ch().value);
  ev(card(0).querySelector('[aria-label="Max Charges"]'), '5'); await wait(20);
  ok(ch().value === '5' && ch().max === '5', 'setting Max Charges fills charges: ' + ch().value);
  ev(ch(), '9'); ok(ch().value === '5', 'charges cannot exceed max');
  ev(ch(), '-3'); ok(ch().value === '0', 'charges cannot go below 0');
  ev(ch(), '2'); ev(card(0).querySelector('[aria-label="Max Charges"]'), '3'); await wait(20);
  ok(ch().value === '2', 'lower charges kept when max changes');
  ev(card(0).querySelector('[aria-label="Max Charges"]'), '1'); await wait(20);
  ok(ch().value === '1', 'max lowered under charges pulls charges down');
  for (const [k, v] of [['Magic Type', 'Wand'], ['Magic Attunement', 'Mage'], ['Magic Effect', 'Zaps']]) { const el = card(0).querySelector(`[aria-label="${k}"]`); ok(!!el, 'field ' + k); if (el) ev(el, v); }
  const sp = card(0).querySelector('[aria-label="Spellbook"]'); sp.checked = true; sp.dispatchEvent(new w.Event('input', { bubbles: true }));
  await wait(700);
  const st = (await b.listCharacters()).find((x) => x.id === c.id).items[0];
  ok(st.magic && st.charges === 1 && st.magicProps.maxCharges === 1 && st.magicProps.type === 'Wand' && st.magicProps.attunement === 'Mage' && st.magicProps.effect === 'Zaps' && st.magicProps.spellbook === true, 'saved: ' + JSON.stringify(st));
  ok(card(1).querySelectorAll('.iline input.num').length === 1, 'other item unaffected');
  mcb().checked = false; mcb().dispatchEvent(new w.Event('change', { bubbles: true })); await wait(30);
  ok(card(0).querySelectorAll('.iline input.num').length === 1 && !card(0).querySelector('.wpgrid'), 'unticking hides charges and fields');
  ok(w.__errors.length === 0, 'no script errors: ' + w.__errors.join('|'));
  done();
})();
